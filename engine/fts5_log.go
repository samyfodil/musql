import "math"

// fts5Log is the natural logarithm FTS5's bm25() uses for its IDF term.
//
// It is not math.Log: C SQLite calls the platform libm, and the two differ in
// the last bit for about 1% of inputs, which bm25 scores would show. This is
// the table-driven algorithm that libm uses, so results match it bit for bit.
// Keep the operation order as written; reassociating any sum changes the bits.
//
// x is split as 2^k * z with z near a table point c, and
// log(x) = k*ln2 + log(c) + log1p(z/c - 1), the last term by polynomial.
// Inputs within about 6% of 1 take a longer polynomial instead.
func fts5Log(x float64) float64 {
	ix := math.Float64bits(x)
	if ix-logNearOneLo < logNearOneHi-logNearOneLo {
		return logNearOne(x, ix)
	}

	if top := uint32(ix >> 48); top-0x0010 >= 0x7ff0-0x0010 {
		switch {
		case ix<<1 == 0:
			return math.Inf(-1)
		case ix == math.Float64bits(math.Inf(1)):
			return x
		case top&0x8000 != 0 || top&0x7ff0 == 0x7ff0:
			// Negative or NaN. (x-x)/(x-x) yields the same NaN bits libm
			// returns, which math.NaN() does not.
			return (x - x) / (x - x)
		}
		// Subnormal: scale by 2^52 and take 52 back off the exponent.
		ix = math.Float64bits(x*0x1p52) - 52<<52
	}

	tmp := ix - logOff
	e := logTable[(tmp>>(52-logTableBits))&(1<<logTableBits-1)]
	k := float64(int64(tmp) >> 52)
	z := math.Float64frombits(ix - tmp&(0xfff<<52))

	r := (z - e.chi - e.clo) * e.invc
	w := k*logLn2Hi + e.logc
	hi := w + r
	lo := w - hi + r + k*logLn2Lo

	a := &logPoly
	r2 := r * r
	return lo + r2*a[0] + r*r2*(a[1]+r*a[2]+r2*(a[3]+r*a[4])) + hi
}

// logNearOne handles x in [1-0x1p-4, 1+0x1.09p-4), where r = x-1 is small and
// the table step would lose precision.
func logNearOne(x float64, ix uint64) float64 {
	if ix == math.Float64bits(1) {
		return 0
	}
	b := &logPoly1
	r := x - 1
	r2 := r * r
	r3 := r * r2
	y := r3 * (b[1] + r*b[2] + r2*b[3] + r3*(b[4]+r*b[5]+r2*b[6]+r3*(b[7]+r*b[8]+r2*b[9]+r3*b[10])))
	// Split r so r*r*b[0] is computed without rounding error.
	w := r * 0x1p27
	rhi := r + w - w
	rlo := r - rhi
	w = rhi * rhi * b[0]
	hi := r + w
	lo := r - hi + w
	lo += b[0] * rlo * (rhi + r)
	y += lo
	return y + hi
}

const (
	logTableBits = 7
	logOff       = 0x3fe6000000000000 // z is reduced into [logOff, 2*logOff)

	logLn2Hi = 0.6931471805598903
	logLn2Lo = 5.497923018708371e-14
)

var (
	logNearOneLo = math.Float64bits(1 - 0x1p-4)
	logNearOneHi = math.Float64bits(1 + 0x1.09p-4)
)

