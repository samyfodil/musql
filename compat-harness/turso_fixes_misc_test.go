// TestSharedCTEBodySweep: C runs a CTE body once, for every reference to share,
// when it is AS MATERIALIZED or referenced twice or more (select.c:7276, :8018);
// only the comparison is printed, so the answer is the same on every run.
func TestSharedCTEBodySweep(t *testing.T) {
	var cases [][]string
	// AS NOT MATERIALIZED is left out: a volatile FROM-less body referenced twice
	// is declined (vdbe.runCTEOnce), because C shares it between the two items of a
	// join and not between separate subqueries.
	for _, hint := range []string{"", "MATERIALIZED "} {
		for _, q := range []string{
			"SELECT (SELECT r FROM t) = (SELECT r FROM t)",
			"SELECT a.r = b.r FROM t a, t b",
			"SELECT a.r = b.r FROM t a JOIN t b",
			"SELECT (SELECT r FROM t) = r FROM t",
			"SELECT r = r FROM t",
			"SELECT 1 WHERE (SELECT r FROM t) = (SELECT r FROM t)",
			"SELECT (SELECT r FROM t) = 0 FROM (SELECT 1 UNION ALL SELECT 2)",
			"SELECT count(DISTINCT (SELECT r FROM t)) FROM (SELECT 1 UNION ALL SELECT 2)",
			"SELECT count(DISTINCT r) FROM (SELECT 1 UNION ALL SELECT 2), t",
		} {
			cases = append(cases, []string{"WITH t AS " + hint + "(SELECT random() AS r) " + q})
		}
	}
	sweepAll(t, cases)
}

// TestDetachInTransactionSweep: DETACH of a database the open transaction read
// or wrote is "database aux is locked" (attach.c, sqlite3BtreeTxnState).
func TestDetachInTransactionSweep(t *testing.T) {
	var cases [][]string
	pre := []string{"ATTACH ':memory:' AS aux", "CREATE TABLE aux.t2(y)", "CREATE TABLE m(x)", "INSERT INTO aux.t2 VALUES(1)"}
	for _, begin := range []string{"BEGIN", "BEGIN IMMEDIATE", "SAVEPOINT s"} {
		for _, use := range []string{"", "SELECT * FROM aux.t2", "SELECT * FROM m", "SELECT * FROM t2", "SELECT count(*) FROM aux.t2", "SELECT * FROM aux.sqlite_master"} {
			for _, end := range []string{"", "COMMIT", "ROLLBACK"} {
				s := append(append([]string(nil), pre...), begin)
				if use != "" {
					s = append(s, use)
				}
				s = append(s, "DETACH aux")
				if end != "" {
					s = append(s, end, "DETACH aux")
				}
				s = append(s, "SELECT count(*) FROM pragma_database_list")
				cases = append(cases, s)
			}
		}
	}
	sweepAll(t, cases)
}

// TestAddColumnHexMinDefaultSweep: a DEFAULT negating 0x8000000000000000 folds to
// a REAL for the rows already stored but cannot be code-generated by an INSERT.
func TestAddColumnHexMinDefaultSweep(t *testing.T) {
	var cases [][]string
	for _, def := range []string{"-0x8000000000000000", "(-0x8000000000000000)", "-0X8000000000000000", "-0x07fffffffffffffff", "-0x8000000000000001", "0x8000000000000000", "-9223372036854775808"} {
		for _, ins := range []string{"INSERT INTO t(a) VALUES(1)", "INSERT INTO t(a,b) VALUES(1,5)", "INSERT INTO t DEFAULT VALUES", "INSERT INTO t(a) SELECT 1"} {
			cases = append(cases, []string{"CREATE TABLE t(a INTEGER)", "INSERT INTO t VALUES(7)",
				"ALTER TABLE t ADD COLUMN b DEFAULT " + def, ins, "SELECT a, quote(b), typeof(b) FROM t ORDER BY rowid"})
		}
	}
	sweepAll(t, cases)
}

// TestWindowMisuseSweep: a window call nested in an aggregate, another window
// call, a FILTER, a PARTITION BY or ORDER BY, or in WHERE/GROUP BY/HAVING is
// "misuse of window function X()".
func TestWindowMisuseSweep(t *testing.T) {
	inner := []string{"row_number() OVER ()", "sum(price) OVER (PARTITION BY name)", "count(*) OVER ()", "max(price) OVER (ORDER BY name)"}
	var cases [][]string
	pre := []string{"CREATE TABLE products(name, price)", "INSERT INTO products VALUES('a',1),('b',2),('a',3)"}
	for _, in := range inner {
		for _, shape := range []string{
			"SELECT sum(%s) FROM products",
			"SELECT sum(%s) FROM products GROUP BY name",
			"SELECT sum(%s) OVER () FROM products",
			"SELECT max(price) OVER (PARTITION BY %s) FROM products",
			"SELECT max(price) OVER (ORDER BY %s) FROM products",
			"SELECT sum(price) FILTER (WHERE %s = 1) OVER () FROM products",
			"SELECT name FROM products GROUP BY %s",
			"SELECT name FROM products WHERE %s > 0",
			"SELECT name, count(*) FROM products GROUP BY name HAVING %s > 0",
			"SELECT first_value(%s) OVER (ORDER BY name) FROM products",
			"SELECT count(*) FROM products ORDER BY sum(%s)",
			"SELECT %s FROM products",
			"SELECT price FROM products ORDER BY %s",
		} {
			cases = append(cases, append(append([]string(nil), pre...), fmt.Sprintf(shape, in)))
		}
	}
	for _, q := range []string{
		"SELECT ROW_NUMBER(1) OVER () FROM products",
		"SELECT Rank(1) OVER (ORDER BY name) FROM products",
		"SELECT NTILE() OVER (ORDER BY name) FROM products",
		"SELECT sum(CASE WHEN price THEN 1 ELSE (1, 1) END) OVER () FROM products",
		"SELECT count(*) FROM products ORDER BY SUM(CASE WHEN price THEN (1, 1) ELSE 1 END) OVER ()",
	} {
		cases = append(cases, append(append([]string(nil), pre...), q))
	}
	sweepAll(t, cases)
}

// TestNamedWindowChainSweep: a WINDOW clause chains each definition after the
// first onto the definitions written before it (sqlite3WindowChain), the latest
// of a repeated name wins, and OVER win takes the window whole where OVER (win
// ...) refines it.
func TestNamedWindowChainSweep(t *testing.T) {
	pre := []string{"CREATE TABLE t(g, v)", "INSERT INTO t VALUES(1,1),(1,2),(2,3),(2,4)"}
	var cases [][]string
	for _, clause := range []string{
		"w2 AS (w3 ORDER BY v), w3 AS (PARTITION BY g)",
		"w1 AS (PARTITION BY g), w2 AS (nope ORDER BY v)",
		"w1 AS (ORDER BY v ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW), w2 AS (w1)",
		"w1 AS (PARTITION BY g), w1 AS (PARTITION BY v)",
		"w1 AS (PARTITION BY g), w2 AS (w1 ORDER BY v), w3 AS (w2)",
		"w1 AS (PARTITION BY g ORDER BY v), w2 AS (w1 ORDER BY v)",
		"w1 AS (PARTITION BY g ORDER BY v), w2 AS (w1 PARTITION BY v)",
		"w1 AS (ORDER BY v), w2 AS (w1 ROWS BETWEEN 1 PRECEDING AND CURRENT ROW)",
		"w1 AS (ORDER BY v ROWS BETWEEN 1 PRECEDING AND CURRENT ROW), w2 AS (ORDER BY v), w3 AS (w2 ROWS 1 PRECEDING)",
		"w1 AS (w1 ORDER BY v)",
		"w1 AS (ORDER BY v), w1 AS (ORDER BY g)",
	} {
		for _, over := range []string{"OVER w1", "OVER w2", "OVER w3", "OVER (w1)", "OVER (w1 ORDER BY v)", "OVER (w2 ROWS 1 PRECEDING)", "OVER (w1 ROWS 1 PRECEDING)", "OVER (w3)"} {
			cases = append(cases, append(append([]string(nil), pre...), "SELECT sum(v) "+over+" FROM t WINDOW "+clause))
		}
		cases = append(cases, append(append([]string(nil), pre...), "SELECT v FROM t WINDOW "+clause))
	}
	sweepAll(t, cases)
}

// TestLagLeadAheadSweep: lag()'s frame ends at the current row, so C returns a
// row having buffered only the next one; a negative offset looks ahead and finds
// just that.
func TestLagLeadAheadSweep(t *testing.T) {
	pre := []string{"CREATE TABLE v(x INTEGER, g INTEGER, o INTEGER)", "INSERT INTO v VALUES(1,1,-1),(2,1,2),(3,1,-2),(4,2,1),(5,2,-3),(6,2,0),(7,2,5)"}
	var cases [][]string
	for _, call := range []string{"lag(x)", "lag(x,-1)", "lag(x,-2)", "lag(x,-3)", "lag(x,0)", "lag(x,o)", "lag(x,o,-99)", "lag(x,-1,-99)", "lag(x,-2,-99)",
		"lead(x)", "lead(x,-1)", "lead(x,-3)", "lead(x,o)", "lead(x,2,-99)", "lag(x,NULL)", "lag(x,1.5)", "lag(x,'-1')"} {
		for _, over := range []string{"OVER (ORDER BY x)", "OVER (PARTITION BY g ORDER BY x)", "OVER (PARTITION BY g ORDER BY x DESC)", "OVER (ORDER BY x ROWS BETWEEN 1 PRECEDING AND 1 FOLLOWING)"} {
			cases = append(cases, append(append([]string(nil), pre...), "SELECT x, "+call+" "+over+" FROM v ORDER BY x"))
		}
	}
	sweepAll(t, cases)
}
