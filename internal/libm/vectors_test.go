// TestGlibcVectors runs both builds of every function on glibcVectors.
func TestGlibcVectors(t *testing.T) {
	defer func(f bool) { fused = f }(fused)
	for _, v := range glibcVectors {
		fn := refFuncs[v.fn]
		x, y := math.Float64frombits(v.x), math.Float64frombits(v.y)
		for _, f := range []bool{false, true} {
			fused = f
			want := v.plain
			if f {
				want = v.fused
			}
			got := fn(x, y)
			if math.Float64bits(got) != want && !(got != got && math.IsNaN(math.Float64frombits(want))) {
				t.Errorf("fused=%v %s(%x, %x) = %x, glibc %x", f, v.fn, x, y, got, math.Float64frombits(want))
			}
		}
	}
}
